POR_NOME = {m["nome"].casefold(): m for m in BESTIARIO}


def listar_monstros(*, tipo: str | None = None, nd: str | None = None) -> list[dict]:
    """Lista cópias dos monstros, opcionalmente filtrados por tipo ou ND."""
    tipo = tipo.casefold() if tipo else None
    nd = str(nd) if nd is not None else None
    return [m.copy() for m in BESTIARIO if (tipo is None or m["tipo"] == tipo) and (nd is None or m["nd"] == nd)]


def consultar_monstro(nome: str) -> dict | None:
    """Consulta um monstro por nome, sem alterar o catálogo."""
    m = POR_NOME.get(str(nome).casefold())
    return m.copy() if m else None


def consultar_bloco_completo(nome: str) -> dict | None:
    """Consulta o registro estrutural junto com o bloco integral do monstro."""
    return consultar_monstro(nome)


def secao_monstro(nome: str, secao: str) -> str | None:
    """Retorna uma seção textual: cabecalho, tracos, acoes, acoes_bonus, reacoes ou acoes_lendarias."""
    monstro = consultar_monstro(nome)
    if monstro is None:
        return None
    chave = str(secao).lower()
    if chave not in {"cabecalho", "tracos", "acoes", "acoes_bonus", "reacoes", "acoes_lendarias", "texto_bloco"}:
        raise ValueError("Seção de monstro desconhecida")
    return monstro.get(chave, "")


def xp_por_nd(nd: str | int) -> int:
    """Retorna o XP oficial associado ao ND; aceita ND inteiro ou fracionário."""
    chave = str(nd)
    if chave not in XP_POR_ND:
        raise ValueError("ND inexistente na tabela do SRD 5.2.1")
    return XP_POR_ND[chave]


def xp_encontro(nomes: list[str]) -> int:
    """Soma o XP dos monstros de um encontro, sem aplicar multiplicadores."""
    total = 0
    for nome in nomes:
        monstro = consultar_monstro(nome)
        if monstro is None:
            raise ValueError(f"Monstro desconhecido: {nome}")
        total += monstro["xp"]
    return total


def _valor_nd(nd: str) -> float:
    return float(nd) if "/" not in str(nd) else float(str(nd).split("/", 1)[0]) / float(str(nd).split("/", 1)[1])


def sugerir_monstros(fatos: dict) -> list[dict]:
    """Retorna candidatos do catálogo para o MJ escolher, sem criar um encontro."""
    tipos = {str(x).casefold() for x in fatos.get("tipos", ([fatos["tipo"]] if fatos.get("tipo") else []))}
    tamanhos = {str(x).casefold() for x in fatos.get("tamanhos", ([fatos["tamanho"]] if fatos.get("tamanho") else []))}
    alinhamentos = {str(x).casefold() for x in fatos.get("alinhamentos", [])}
    nds = {str(x) for x in fatos.get("nds", [])}
    nd_min = fatos.get("nd_min")
    nd_max = fatos.get("nd_max")
    excluir = {str(x).casefold() for x in fatos.get("excluir", [])}
    candidatos = []
    for monstro in BESTIARIO:
        if tipos and monstro["tipo"] not in tipos:
            continue
        if tamanhos and monstro["tamanho"].casefold() not in tamanhos:
            continue
        if alinhamentos and monstro["alinhamento"] not in alinhamentos:
            continue
        if nds and monstro["nd"] not in nds:
            continue
        if nd_min is not None and _valor_nd(monstro["nd"]) < _valor_nd(str(nd_min)):
            continue
        if nd_max is not None and _valor_nd(monstro["nd"]) > _valor_nd(str(nd_max)):
            continue
        if monstro["nome"].casefold() in excluir:
            continue
        candidatos.append({k: monstro[k] for k in ("nome", "tamanho", "tipo", "alinhamento", "ca", "pv", "nd", "xp")})
    candidatos.sort(key=lambda m: (_valor_nd(m["nd"]), m["nome"].casefold()))
    limite = fatos.get("limite")
    return candidatos[: int(limite)] if limite is not None else candidatos


def validar_uso_monstro(fatos: dict) -> dict:
    """Valida uso das regras oficiais sem opinar sobre história ou narração."""
    nome = str(fatos.get("nome", ""))
    monstro = consultar_monstro(nome)
    if monstro is None:
        return {"resultado": "bloqueado", "motivo": "monstro_desconhecido"}
    campos_protegidos = {"ca", "pv", "dados_pv", "nd", "xp", "tipo", "tamanho", "alinhamento", "texto_bloco"}
    alteracoes = set(fatos.get("alteracoes", {}))
    proibidos = sorted(alteracoes & campos_protegidos)
    if proibidos:
        return {"resultado": "bloqueado", "motivo": "alteracao_de_dado_oficial", "campos": proibidos}
    return {
        "resultado": "validado",
        "nome": monstro["nome"],
        "origem": "SRD 5.2.1",
        "regras_oficiais": True,
        "narrativa": "não avaliada pelo motor",
        "criatividade_do_mj": "preservada",
    }


def resolver_bestiario(fatos: dict) -> dict:
    """Resolve operações auditáveis sobre o catálogo do bestiário."""
    operacao = str(fatos.get("operacao", "consultar")).lower()
    if operacao == "consultar":
        monstro = consultar_monstro(fatos.get("nome", ""))
        return (
            {"resultado": "encontrado", "monstro": monstro}
            if monstro
            else {"resultado": "bloqueado", "motivo": "monstro_desconhecido"}
        )
    if operacao in {"bloco_completo", "secao"}:
        nome = fatos.get("nome", "")
        monstro = consultar_bloco_completo(nome)
        if monstro is None:
            return {"resultado": "bloqueado", "motivo": "monstro_desconhecido"}
        if operacao == "bloco_completo":
            return {"resultado": "encontrado", "monstro": monstro}
        return {
            "resultado": "encontrado",
            "nome": monstro["nome"],
            "secao": fatos.get("secao", ""),
            "texto": secao_monstro(nome, fatos.get("secao", "")),
        }
    if operacao == "listar":
        monstros = listar_monstros(tipo=fatos.get("tipo"), nd=fatos.get("nd"))
        return {"resultado": "listado", "quantidade": len(monstros), "monstros": monstros}
    if operacao == "sugerir":
        candidatos = sugerir_monstros(fatos)
        return {
            "resultado": "candidatos_encontrados" if candidatos else "nenhum_candidato",
            "quantidade": len(candidatos),
            "candidatos": candidatos,
            "escolha": "MJ",
            "origem": "SRD 5.2.1",
        }
    if operacao == "validar_uso":
        return validar_uso_monstro(fatos)
    if operacao == "xp_nd":
        return {"resultado": "resolvido", "nd": str(fatos["nd"]), "xp": xp_por_nd(fatos["nd"])}
    if operacao == "xp_encontro":
        nomes = [str(nome) for nome in fatos.get("nomes", [])]
        return {"resultado": "resolvido", "monstros": nomes, "xp_total": xp_encontro(nomes)}
    return {"resultado": "bloqueado", "motivo": "operacao_desconhecida"}
